export const GLYPH_HEIGHT = 7
export const LINE_HEIGHT = 10

export function normalize(text: string): string {
  return text.toUpperCase()
}

export function hasGlyph(ch: string): boolean {
  return ch in G
}

export function glyph(ch: string): string[] {
  return G[ch] ?? G['?']
}

export function measure(text: string): number {
  let w = 0
  for (const ch of normalize(text)) w += glyph(ch)[0].length + 1
  return Math.max(0, w - 1)
}

/** Draws text with its top-left at (x, y); 1 font pixel = `scale` canvas pixels. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale = 1) {
  let cx = x
  for (const ch of normalize(text)) {
    const rows = glyph(ch)
    for (let r = 0; r < rows.length; r++) {
      const row = rows[r]
      for (let c = 0; c < row.length; c++) if (row[c] === '1') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale)
    }
    cx += (rows[0].length + 1) * scale
  }
}

/** Greedy word wrap measured in font pixels. */
export function wrap(text: string, maxWidth: number): string[] {
  const words = text.split(/\s+/)
  const lines: string[] = []
  let line = ''
  for (const w of words) {
    const next = line ? `${line} ${w}` : w
    if (measure(next) > maxWidth && line) {
      lines.push(line)
      line = w
    } else line = next
  }
  if (line) lines.push(line)
  return lines
}
