export function icon(name: keyof typeof ICONS | string): string {
  const rows = ICONS[name] ?? ICONS.close
  let rects = ''
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`
  })
  return `<svg viewBox="0 0 11 11" fill="currentColor" aria-hidden="true">${rects}</svg>`
}
